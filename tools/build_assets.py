#!/usr/bin/env python3
"""Build a word-trigram model and a tiny 6502 ROM; no third-party packages."""
import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPS = {"lda": (0xA9, "imm"), "ldx": (0xA6, "zp"), "sta": (0x85, "zp"),
       "clc": (0x18, "none"), "adc": (0x69, "imm"), "dex": (0xCA, "none"),
       "cmp": (0xC9, "imm"), "beq": (0xF0, "rel"), "bne": (0xD0, "rel"),
       "bcc": (0x90, "rel"), "brk": (0x00, "none")}


def assemble(source):
    """Two passes for only this kernel's documented ca65 instruction subset.

    CI also assembles with ca65/ld65 and compares bytes, so this builder isn't
    its own only oracle. BRK is one byte here and a host stop in the interpreter.
    """
    labels, instructions, offset = {}, [], 0
    for line in source.splitlines():
        line = line.split(";", 1)[0].strip()
        if not line or line == '.segment "CODE"':
            continue
        if line.endswith(":"):
            name = line[:-1]
            if name in labels:
                raise ValueError("Duplicate label")
            labels[name] = offset
            continue
        parts = line.split()
        opcode, mode = OPS[parts[0]]
        if len(parts) != (1 if mode == "none" else 2):
            raise ValueError("Unexpected operand count")
        instructions.append((offset, opcode, mode, parts[1] if len(parts) == 2 else ""))
        offset += 1 if mode == "none" else 2
    result = []
    for offset, opcode, mode, operand in instructions:
        result.append(opcode)
        if mode == "none":
            continue
        if mode == "rel":
            value = labels[operand] - (offset + 2)
            if not -128 <= value <= 127:
                raise ValueError("Branch out of range")
            value &= 255
        elif mode == "imm":
            if not operand.startswith("#"):
                raise ValueError("Expected immediate")
            value = int(operand[1:])
        else:
            if not operand.startswith("$"):
                raise ValueError("Expected zero-page address")
            value = int(operand[1:], 16)
        if not 0 <= value <= 255:
            raise ValueError("Operand outside byte range")
        result.append(value)
    return result


def assets():
    raw = (ROOT / "model/corpus.txt").read_bytes()
    sentences = raw.decode().splitlines()
    transitions = defaultdict(Counter)
    vocabulary = set()
    for sentence in sentences:
        tokens = sentence.split()
        vocabulary.update(tokens)
        padded = ["<s>", "<s>", *tokens, "</s>"]
        for i in range(len(padded) - 2):
            transitions["|".join(padded[i:i+2])][padded[i+2]] += 1
    model = {
        "format": "psyche-word-trigram-v1", "sentences": len(sentences),
        "vocabulary": len(vocabulary), "corpusSha256": hashlib.sha256(raw).hexdigest(),
        "transitions": {key: sorted(counts.items()) for key, counts in sorted(transitions.items())},
    }
    rom = assemble((ROOT / "native/6502/kernel.s").read_text())
    header = "// Generated by tools/build_assets.py; SPDX-License-Identifier: Apache-2.0\n"
    return {"web/model.js": header + "globalThis.PsycheModel = " + json.dumps(model, separators=(",", ":")) + ";\n",
            "web/kernel-rom.js": header + "globalThis.PsycheROM = " + json.dumps(rom) + ";\n"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in assets().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != text.encode():
                raise SystemExit(f"Stale generated asset: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode())
    print("Generated assets match sources." if args.check else "Built model and 6502 ROM.")
